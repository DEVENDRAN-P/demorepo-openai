let added = 0;
for (const lang of langs) {
  const file = path.join(localesDir, `${lang}.json`);
  const text = fs.readFileSync(file, 'utf8');
  const data = JSON.parse(text);
  const entries = Object.entries(ADDITIONS[lang] || {}).filter(([k]) => !(k in data));
  if (entries.length === 0) {
    console.log(`${lang}.json: no new keys (all present)`);
    continue;
  }
  // Preserve the original bytes up to the root closing brace, then append.
  const idx = text.lastIndexOf('\n}');
  if (idx === -1) throw new Error(`Unexpected structure in ${lang}.json`);
  const head = text.slice(0, idx).replace(/\s+$/, '');
  const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n');
  fs.writeFileSync(file, `${head},\n${body}\n}\n`);
  added += entries.length;
  console.log(`${lang}.json: added ${entries.length} keys`);
}
